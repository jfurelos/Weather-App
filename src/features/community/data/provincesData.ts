// Generador genérico de comarcas de respaldo para cualquier provincia que no tenga lista manual
export function getComarcasForProvince(provinceName: string): Comarca[] {
  const normKey = normalizeProvinceName(provinceName);
  if (PROVINCE_COMARCAS_MAP[normKey]) {
    return PROVINCE_COMARCAS_MAP[normKey];
  }

  // Comarcas por defecto si no están especificadas manualmente
  return [
    {
      id: `${normKey}-capital`,
      provinceId: normKey,
      provinceName,
      name: `Área Central de ${provinceName}`,
      description: `Zona metropolitana, capital y principales núcleos urbanos de ${provinceName}`,
      activeCount: 24,
    },
    {
      id: `${normKey}-norte`,
      provinceId: normKey,
      provinceName,
      name: `Comarca Norte de ${provinceName}`,
      description: `Sierras y municipios septentrionales de ${provinceName}`,
      activeCount: 14,
    },
    {
      id: `${normKey}-sur`,
      provinceId: normKey,
      provinceName,
      name: `Comarca Sur de ${provinceName}`,
      description: `Valles y llanuras meridionales de ${provinceName}`,
      activeCount: 12,
    },
  ];
}

export function normalizeProvinceName(name: string): string {
  return name
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/\s+/g, '_')
    .replace(/[^a-z0-9_]/g, '');
}
